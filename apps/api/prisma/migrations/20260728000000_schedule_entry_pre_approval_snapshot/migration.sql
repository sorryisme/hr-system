-- F-04. schedule_entry.pre_approval_snapshot 신설 — 결재 건이 셀을 최초로 덮어쓰기
--       직전 상태의 스냅샷(JSON). 반려/취소 확정 시 이 값으로 복구하고 비운다.
--       NULL이면 사전에 셀 자체가 없었다는 뜻 — 원복은 삭제.
--       (수동/프리셋으로 이미 입력돼 있던 정상 근무를 가반영이 덮어쓴 뒤 반려/취소되어도
--        원래 근무가 사라지지 않도록 함 — 코드 리뷰 지적사항 반영)
--
-- NULL 허용 컬럼 추가 1건이라 기존 데이터 재작성 없음(비파괴).
-- =============================================================

ALTER TABLE schedule_entry
  ADD COLUMN pre_approval_snapshot JSON NULL
    COMMENT '[반려/취소 원복 §4.10] source_request_id 건이 셀을 최초로 덮어쓰기 직전 상태의 스냅샷.
             반려/취소 확정 시 이 값으로 복구하고 비운다. NULL이면 사전에 셀 자체가 없었다는 뜻(원복=삭제)'
    AFTER source_ledger_id;
